/** Mundari (unr) is the pilot vernacular: registered end-to-end, strings fall back to English. */
const dictionaries: Record<LanguageCode, UiStrings> = { en, hi, ta, unr: en };

interface I18nContextValue {
  language: LanguageCode;
  setLanguage: (code: LanguageCode) => void;
  t: (key: UiKey) => string;
  info: (typeof LANGUAGES)[number];
}

const I18nContext = createContext<I18nContextValue | null>(null);
const STORAGE_KEY = 'aieses.language';

export function I18nProvider({ children, initial }: { children: ReactNode; initial?: LanguageCode }) {
  const [language, setLanguageState] = useState<LanguageCode>(() => {
    const stored = typeof localStorage !== 'undefined' ? (localStorage.getItem(STORAGE_KEY) as LanguageCode | null) : null;
    return stored && dictionaries[stored] ? stored : initial ?? 'en';
  });
  useEffect(() => {
    document.documentElement.lang = language === 'unr' ? 'en' : language;
  }, [language]);
  const setLanguage = useCallback((code: LanguageCode) => {
    setLanguageState(code);
    localStorage.setItem(STORAGE_KEY, code);
  }, []);
  const value = useMemo<I18nContextValue>(
    () => ({
      language,
      setLanguage,
      t: (key) => dictionaries[language][key] ?? en[key] ?? key,
      info: LANGUAGES.find((l) => l.code === language) ?? LANGUAGES[0],
    }),
    [language, setLanguage],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}

